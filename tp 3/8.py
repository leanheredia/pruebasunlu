#8. Escribe un algoritmo que, conociendo las notas de los dos parciales de un alumno de la asignatura Introducción a la Programación, muestre en pantalla su promedio. 

nota_parcial1 = float(input('Ingresa la nota del primer parcial'))
nota_parcial2 = float(input('Ingresa la nota del segundo parcial'))
promedio = (nota_parcial1 + nota_parcial2) / 2

print('El promedio de ambas notas es:', promedio)